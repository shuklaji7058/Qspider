public class AsciiDemo {
    public static void main(String[] args) {

        char ch1 = 65;
        char ch2 = 97;

        System.out.println(ch1);
        System.out.println(ch2);

        System.out.println((int)'A');
        System.out.println((int)'a');

        System.out.println((char)66);
        System.out.println((char)99);
    }
}